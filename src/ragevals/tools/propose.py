"""Propose candidate gold questions from the corpus, for a human to curate.

This script does **not** write your gold set. It writes a worksheet. The
distinction is the whole point: a gold set generated by a model and evaluated
by a model measures the agreement of two models, not the correctness of a
system. Candidates come out marked ``status: DRAFT`` with the exact (source,
page) they were drawn from, so curation is a reading task rather than a
writing task -- which is what makes 80 items achievable in an afternoon.

Selection favours passages that make *checkable* questions: those containing
obligations ("shall", "must"), numbers, deadlines, or legal cross-references.
Vague prose makes vague questions, and vague questions make a gold set whose
scores nobody can argue with because nobody can interpret them.

It also drafts unanswerable candidates by pairing corpus vocabulary with
subject matter the corpus does not cover. Those need the most human attention:
a good unanswerable question is *plausible* -- it looks like it should be in
the corpus -- otherwise refusal accuracy is measured against straw men.
"""
from __future__ import annotations

import random
import re
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import yaml

from ..config import Config
from ..ingest.chunking import Chunk
from ..logging_utils import get_logger

log = get_logger(__name__)

OBLIGATION_RE = re.compile(r"\b(shall|must|is required to|may not|is prohibited|"
                           r"has the right to|are obliged)\b", re.IGNORECASE)
NUMBER_RE = re.compile(r"\b\d+(?:[.,]\d+)?\s*(?:hours?|days?|months?|years?|%|"
                       r"percent|million|EUR|euro)\b", re.IGNORECASE)
REFERENCE_RE = re.compile(r"\b(?:Article|Annex|Section|Recital)\s+\d+", re.IGNORECASE)

TEMPLATES = [
    "According to {section}, what {verb} {subject}?",
    "What does {section} require in relation to {subject}?",
    "Under {source}, what is the rule on {subject}?",
    "What obligation does {section} place on {actor}?",
]

UNANSWERABLE_TEMPLATES = [
    "What penalty does {section} set for {absent_topic}?",
    "How does {source} regulate {absent_topic}?",
    "What does {section} say about {absent_topic} in the United States?",
    "Which deadline applies to {absent_topic} under {source}?",
    "What is the appeal procedure for {absent_topic}?",
]

ABSENT_TOPICS = [
    "cryptocurrency mining permits", "maritime cargo insurance",
    "paediatric vaccine scheduling", "municipal parking enforcement",
    "agricultural subsidy quotas", "spacecraft frequency licensing",
    "professional football transfer fees", "dental implant reimbursement",
    "submarine cable landing rights", "wine appellation labelling",
]

ACTORS = ["the provider", "the controller", "the deployer", "the processor",
          "the supervisory authority", "the importer"]


def _salient_sentences(chunk: Chunk, limit: int = 2) -> list[str]:
    sentences = [s.strip() for s in re.split(r"(?<=[.;])\s+", chunk.text) if len(s.strip()) > 60]
    scored = []
    for sentence in sentences:
        score = (2.0 * bool(OBLIGATION_RE.search(sentence))
                 + 1.5 * bool(NUMBER_RE.search(sentence))
                 + 1.0 * bool(REFERENCE_RE.search(sentence))
                 + min(len(sentence), 320) / 400.0)
        scored.append((score, sentence))
    scored.sort(key=lambda t: -t[0])
    return [s for score, s in scored[:limit] if score > 1.0]


def _subject_of(sentence: str) -> str:
    words = re.findall(r"[A-Za-z][A-Za-z-]{3,}", sentence)
    stop = {"shall", "must", "that", "this", "which", "with", "from", "under",
            "their", "there", "where", "when", "they", "been", "have", "such"}
    keep = [w for w in words if w.lower() not in stop][:6]
    return " ".join(keep[:4]).lower() or "the requirement"


def propose_questions(cfg: Config, n: int = 60, seed: int = 7,
                      out_path: str | Path | None = None,
                      chunks: Sequence[Chunk] | None = None,
                      unanswerable_share: float = 0.25) -> list[dict[str, Any]]:
    from ..ingest.pipeline import build_chunks

    rng = random.Random(seed)
    if chunks is None:
        chunks, _ = build_chunks(cfg)
    chunks = list(chunks)
    rng.shuffle(chunks)

    n_unanswerable = int(round(n * unanswerable_share))
    n_answerable = n - n_unanswerable
    items: list[dict[str, Any]] = []

    index = 1
    for chunk in chunks:
        if len(items) >= n_answerable:
            break
        sentences = _salient_sentences(chunk)
        if not sentences:
            continue
        sentence = sentences[0]
        section = chunk.section or f"{chunk.source} p.{chunk.page}"
        template = rng.choice(TEMPLATES)
        question = template.format(
            section=section, source=chunk.source, subject=_subject_of(sentence),
            verb="is required of" if OBLIGATION_RE.search(sentence) else "applies to",
            actor=rng.choice(ACTORS))
        items.append({
            "id": f"q{index:03d}",
            "question": re.sub(r"\s+", " ", question).strip(),
            "reference_answer": f"DRAFT -- rewrite from the source: {sentence[:400]}",
            "answerable": True,
            "gold_sources": [{"source": chunk.source, "page": chunk.page}],
            "tags": [chunk.source.rsplit(".", 1)[0]],
            "difficulty": "medium",
            "notes": "DRAFT: verify the cited page, rewrite the answer in your own "
                     "words, and delete this note.",
            "status": "DRAFT",
        })
        index += 1

    sources = sorted({c.source for c in chunks})
    sections = [c.section for c in chunks if c.section] or ["the regulation"]
    for _ in range(n_unanswerable):
        template = rng.choice(UNANSWERABLE_TEMPLATES)
        items.append({
            "id": f"q{index:03d}",
            "question": template.format(section=rng.choice(sections),
                                        source=rng.choice(sources),
                                        absent_topic=rng.choice(ABSENT_TOPICS)),
            "reference_answer": "",
            "answerable": False,
            "gold_sources": [],
            "tags": ["unanswerable"],
            "difficulty": "medium",
            "notes": "DRAFT: confirm the corpus really does not answer this, and "
                     "make the question plausible enough to be a fair test.",
            "status": "DRAFT",
        })
        index += 1

    if len(items) < n:
        log.warning(
            "requested %d candidate(s) but the corpus only yielded %d: %d chunk(s) "
            "carried a question-worthy passage. Ingest more documents, or lower -n.",
            n, len(items), len(chunks))

    rng.shuffle(items)
    for i, item in enumerate(items, start=1):
        item["id"] = f"q{i:03d}"

    if out_path:
        out_path = Path(out_path)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        header = ("# Candidate questions -- DRAFT, not a gold set.\n"
                  "# Curate every item: verify the page, rewrite the reference answer\n"
                  "# in your own words, set 'answerable', then delete the 'status' and\n"
                  "# 'notes' fields. Target ~25% unanswerable items.\n")
        out_path.write_text(
            header + yaml.safe_dump({"items": items}, sort_keys=False,
                                    allow_unicode=True, width=100),
            encoding="utf-8")
        log.info("wrote %d candidate(s) to %s", len(items), out_path)
    return items
